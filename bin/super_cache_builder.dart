#!/usr/bin/env dart
// ignore_for_file: avoid_print
import 'dart:io';

/// super_cache code generator.
///
/// Generates [SuperCacheAdapter] implementations for classes annotated with
/// [@Cacheable] and [@CacheField].
///
/// This is a standalone script.  In a build_runner setup you would replace this
/// with a proper [Builder] in a `super_cache_generator` package.
///
/// **Usage:**
/// ```sh
/// dart run super_cache:super_cache_builder lib/models
/// ```
///
/// The script scans the given directory for `@Cacheable` annotations and
/// emits `*.g.dart` adapter files alongside each source file.
void main(List<String> args) {
  final dir = args.isNotEmpty ? Directory(args[0]) : Directory('lib');

  if (!dir.existsSync()) {
    print('❌  Directory not found: ${dir.path}');
    exit(1);
  }

  print('🔍  Scanning ${dir.path} for @Cacheable classes...');

  var generated = 0;
  for (final file in dir.listSync(recursive: true).whereType<File>()) {
    if (!file.path.endsWith('.dart')) continue;
    if (file.path.endsWith('.g.dart')) continue;

    final source = file.readAsStringSync();
    if (!source.contains('@Cacheable(')) continue;

    final adapters = _generateAdapters(source, file.path);
    if (adapters.isEmpty) continue;

    final outputPath = file.path.replaceFirst('.dart', '.g.dart');
    File(outputPath).writeAsStringSync(_buildGeneratedFile(adapters));
    print('✅  Generated $outputPath');
    generated++;
  }

  print('\n📦  Done — generated $generated adapter file(s).');
}

// ─────────────────────────────────────────────────────────────────────────────
// Parsing
// ─────────────────────────────────────────────────────────────────────────────

const _classPattern =
    r'@Cacheable\(typeId:\s*(\d+)\)\s*class\s+(\w+)';
const _fieldPattern =
    r'@CacheField\((\d+)\)\s+final\s+(\w+\?*)\s+(\w+);';

List<_ClassInfo> _generateAdapters(String source, String filePath) {
  final classes = <_ClassInfo>[];
  final classRe = RegExp(_classPattern);
  final fieldRe = RegExp(_fieldPattern);

  for (final classMatch in classRe.allMatches(source)) {
    final typeId = int.parse(classMatch.group(1)!);
    final className = classMatch.group(2)!;

    // Find all fields between this class declaration and the next top-level
    // declaration (rough heuristic).
    final classStart = classMatch.start;
    final classEnd = _findClassEnd(source, classStart);
    final classBody = source.substring(classStart, classEnd);

    final fields = <_FieldInfo>[];
    for (final fieldMatch in fieldRe.allMatches(classBody)) {
      fields.add(_FieldInfo(
        index: int.parse(fieldMatch.group(1)!),
        type: fieldMatch.group(2)!,
        name: fieldMatch.group(3)!,
      ));
    }
    fields.sort((a, b) => a.index.compareTo(b.index));

    if (fields.isEmpty) continue;
    classes.add(_ClassInfo(
      typeId: typeId,
      className: className,
      fields: fields,
    ));
  }

  return classes;
}

int _findClassEnd(String source, int start) {
  var depth = 0;
  for (var i = start; i < source.length; i++) {
    if (source[i] == '{') depth++;
    if (source[i] == '}') {
      depth--;
      if (depth == 0) return i + 1;
    }
  }
  return source.length;
}

// ─────────────────────────────────────────────────────────────────────────────
// Code generation
// ─────────────────────────────────────────────────────────────────────────────

String _buildGeneratedFile(List<_ClassInfo> classes) {
  final buf = StringBuffer()
    ..writeln('// GENERATED CODE — DO NOT EDIT BY HAND')
    ..writeln('// Generated by super_cache_builder')
    ..writeln()
    ..writeln("import 'package:super_cache/src/codec/binary_reader.dart';")
    ..writeln("import 'package:super_cache/src/codec/binary_writer.dart';")
    ..writeln("import 'package:super_cache/src/codec/type_registry.dart';")
    ..writeln();

  for (final cls in classes) {
    buf.write(_generateAdapter(cls));
  }

  return buf.toString();
}

String _generateAdapter(_ClassInfo cls) {
  final buf = StringBuffer();
  final adapterName = '${cls.className}Adapter';

  buf
    ..writeln('/// Auto-generated [SuperCacheAdapter] for [${cls.className}].')
    ..writeln('final class $adapterName extends SuperCacheAdapter<${cls.className}> {')
    ..writeln('  @override')
    ..writeln('  int get typeId => ${cls.typeId};')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  ${cls.className} read(BinaryReader reader) {')
    ..writeln('    final numFields = reader.readByte();')
    ..writeln('    final fields = <int, dynamic>{};')
    ..writeln('    for (var i = 0; i < numFields; i++) {')
    ..writeln('      final index = reader.readByte();')
    ..writeln('      fields[index] = _readField(reader, index);')
    ..writeln('    }')
    ..writeln('    return ${cls.className}(');

  for (final field in cls.fields) {
    final cast = _castExpression(field.type, 'fields[${field.index}]');
    buf.writeln('      ${field.name}: $cast,');
  }

  buf
    ..writeln('    );')
    ..writeln('  }')
    ..writeln()
    ..writeln('  dynamic _readField(BinaryReader reader, int index) {')
    ..writeln('    switch (index) {');

  for (final field in cls.fields) {
    buf
      ..writeln('      case ${field.index}:')
      ..writeln('        return ${_readExpression(field.type)};');
  }

  buf
    ..writeln('      default:')
    ..writeln('        return null;')
    ..writeln('    }')
    ..writeln('  }')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  void write(BinaryWriter writer, ${cls.className} obj) {')
    ..writeln('    writer.writeByte(${cls.fields.length}); // numFields');

  for (final field in cls.fields) {
    buf
      ..writeln('    writer.writeByte(${field.index});')
      ..writeln('    ${_writeExpression(field.type, 'obj.${field.name}', 'writer')};');
  }

  buf
    ..writeln('  }')
    ..writeln('}')
    ..writeln();

  return buf.toString();
}

String _castExpression(String type, String expr) {
  switch (type) {
    case 'String':   return '$expr as String';
    case 'String?':  return '$expr as String?';
    case 'int':      return '$expr as int';
    case 'int?':     return '$expr as int?';
    case 'double':   return '$expr as double';
    case 'double?':  return '$expr as double?';
    case 'bool':     return '$expr as bool';
    case 'bool?':    return '$expr as bool?';
    case 'DateTime': return '$expr as DateTime';
    case 'Duration': return '$expr as Duration';
    default:
      if (type.startsWith('List<')) return '($expr as List).cast()';
      return expr;
  }
}

String _readExpression(String type) {
  switch (type) {
    case 'String':   return 'reader.readString()';
    case 'String?':  return 'reader.readBool() ? reader.readString() : null';
    case 'int':      return 'reader.readInt64()';
    case 'int?':     return 'reader.readBool() ? reader.readInt64() : null';
    case 'double':   return 'reader.readFloat64()';
    case 'double?':  return 'reader.readBool() ? reader.readFloat64() : null';
    case 'bool':     return 'reader.readBool()';
    case 'bool?':    return 'reader.readBool() ? reader.readBool() : null';
    case 'DateTime':
      return 'DateTime.fromMicrosecondsSinceEpoch(reader.readInt64())';
    case 'Duration':
      return 'Duration(microseconds: reader.readInt64())';
    default:
      if (type.startsWith('List<String>')) {
        return '[for (var i = reader.readUint32(); i-- > 0;) reader.readString()]';
      }
      return 'null';
  }
}

String _writeExpression(String type, String varExpr, String writer) {
  switch (type) {
    case 'String':   return '$writer.writeString($varExpr)';
    case 'String?':
      return '$writer.writeBool($varExpr != null); '
          'if ($varExpr != null) $writer.writeString($varExpr!)';
    case 'int':      return '$writer.writeInt64($varExpr)';
    case 'int?':
      return '$writer.writeBool($varExpr != null); '
          'if ($varExpr != null) $writer.writeInt64($varExpr!)';
    case 'double':   return '$writer.writeFloat64($varExpr)';
    case 'double?':
      return '$writer.writeBool($varExpr != null); '
          'if ($varExpr != null) $writer.writeFloat64($varExpr!)';
    case 'bool':     return '$writer.writeBool($varExpr)';
    case 'bool?':
      return '$writer.writeBool($varExpr != null); '
          'if ($varExpr != null) $writer.writeBool($varExpr!)';
    case 'DateTime':
      return '$writer.writeInt64($varExpr.microsecondsSinceEpoch)';
    case 'Duration':
      return '$writer.writeInt64($varExpr.inMicroseconds)';
    default:
      if (type.startsWith('List<String>')) {
        return '$writer.writeUint32($varExpr.length); '
            'for (final s in $varExpr) $writer.writeString(s)';
      }
      return '// TODO: write $type';
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// Data classes
// ─────────────────────────────────────────────────────────────────────────────

class _ClassInfo {
  const _ClassInfo({
    required this.typeId,
    required this.className,
    required this.fields,
  });

  final int typeId;
  final String className;
  final List<_FieldInfo> fields;
}

class _FieldInfo {
  const _FieldInfo({
    required this.index,
    required this.type,
    required this.name,
  });

  final int index;
  final String type;
  final String name;
}
